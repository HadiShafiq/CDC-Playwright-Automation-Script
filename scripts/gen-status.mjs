// Generates, from registry/:
//   tests/status/en/<module>/<flow>/<NN>-<STATUS>.spec.ts   one spec per status of each flow: runs the flow up to that
//                                                         status and stops, to prepare a transaction for manual testing
//   docs/status-catalog.md                                every status per module, how to reach it, gates on the way
// Run after changing registry/: npm run status:gen      (BM status specs come with the BM phase, after permission)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const MODULES = ['sq', 'dp', 'direct-loa', 'ct', 'fl'];
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const gates = read('registry/gates.json');
const files = MODULES.map((m) => read(`registry/workflows/${m}.json`));
const steps = Object.fromEntries(files.flatMap((d) => Object.entries(d.steps).map(([id, s]) => [id, { id, module: d.module, ...s }])));
const flows = files.flatMap((d) => d.flows.map((f) => ({ ...f, module: d.module })));
const key = (r) => (typeof r === 'string' ? r : r.gate);
const RANK = { execution: 0, documentation: 1, source: 2, unverified: 3 };

const outDir = path.join(root, 'tests', 'status', 'en');
if (fs.existsSync(outDir)) fs.rmSync(outDir, { recursive: true });

const targets = []; // { flow, index, step }
for (const flow of flows)
  flow.steps.forEach((r, index) => {
    if (typeof r === 'string') targets.push({ flow, index, step: steps[r] });
  });

for (const { flow, index, step } of targets) {
  const cp = step.checkpoint;
  const nn = String(index + 1).padStart(2, '0');
  const file = path.join(outDir, flow.module, flow.id, `${nn}-${cp.id}.spec.ts`);
  const rel = path.relative(root, file).split(path.sep).join('/');
  const up = path.relative(path.dirname(file), root).split(path.sep).join('/');
  const path_ = flow.steps.slice(0, index + 1).map((r) => (typeof r === 'string' ? r : `GATE ${r.gate}`)).join(' → ');
  const gatesOnWay = flow.steps.slice(0, index + 1).filter((r) => typeof r === 'object').map((r) => r.gate);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(
    file,
    `// GENERATED by scripts/gen-status.mjs from registry/ — do not edit; run "npm run status:gen" after changing the registry.
//
// Prepare: ${flow.title}
// Stops at: ${cp.id} — ${cp.description} (after ${step.id}, ${step.role})
// Path:     ${path_}${gatesOnWay.length ? `\n// Gates:    ${gatesOnWay.join(', ')} — the run stops there until you record them (npm run qa -- gate …), then resume` : ''}
// Status:   checkpoint verification "${cp.verification}"; displayed status EN: ${cp.displayedStatus.en ?? 'not yet seen'}
//
// Run (manual testing): npx cross-env TEST_ENV=SIT playwright test "${rel}" --project=flows --headed
//   or through the CLI:  npm run qa -- prepare --env sit --flow ${flow.id} --status ${cp.id}
// The documents created (e.g. the LA number) are in the run report and in: npm run qa -- data --env sit
import { test } from '${up}/fixtures/flow';
import { flowItems, flowTags, flowTitle, runItem, setupFlow } from '${up}/support/core/flow-runner';
import { loadRegistry } from '${up}/support/core/workflow-registry';

const LANG = 'EN';
const flow = loadRegistry().flows.get('${flow.id}')!;
const STOP_AT = '${step.id}';

test.describe(\`prepare \${flow.id} → ${cp.id}\`, { tag: [...flowTags(flow, LANG), '@status-${cp.id}', '@prepare'] }, () => {
  const runId = setupFlow(flow, LANG, { to: STOP_AT });
  for (const { item, index, title, details } of flowItems(flow).slice(0, ${index + 1})) {
    test(title, details, async ({ page, appMessages, evidence }, testInfo) => {
      await runItem(flow, item, index, runId(), { page, appMessages, evidence }, testInfo);
    });
  }
});
`,
  );
}

// ---------- docs/status-catalog.md ----------
const L = [
  '# Status catalogue (generated)',
  '',
  'Generated by `npm run status:gen` from `registry/`. Every status (checkpoint) the automation can reach, per module,',
  'and how to prepare a transaction at that status for **manual testing**. Do not edit by hand.',
  '',
  '- **Prepare by CLI:** `npm run qa -- prepare --env sit --status <STATUS>` (picks the best-verified flow; add `--flow <id>` to choose).',
  '- **Prepare by spec:** `npx cross-env TEST_ENV=SIT playwright test "tests/status/en/<module>/<flow>/<NN>-<STATUS>.spec.ts" --headed`.',
  '- The run stops right after the step that reaches the status. Its documents: `npm run qa -- data --env sit` or the run report.',
  '- A path through a **gate** stops there until you record it (`npm run qa -- gate …`), then `npm run qa -- resume`.',
  '- *Displayed status* is the status text read on the application screen; "—" until a run has read it.',
  '',
];
for (const d of files) {
  L.push(`## ${d.module} — ${d.name}`, '', d.description, '');
  L.push('| Status | Meaning | After step (role) | Verified | Displayed EN / BM | Reached by flows (gates on the way) |', '|---|---|---|---|---|---|');
  const byCp = new Map();
  for (const t of targets.filter((t) => t.step.module === d.module)) {
    const k = `${t.step.checkpoint.id}|${t.step.id}`;
    if (!byCp.has(k)) byCp.set(k, []);
    byCp.get(k).push(t);
  }
  for (const [, ts] of byCp) {
    const s = ts[0].step;
    const cp = s.checkpoint;
    ts.sort((a, b) => RANK[a.flow.verification] - RANK[b.flow.verification] || a.index - b.index);
    const via = ts
      .map((t) => {
        const g = t.flow.steps.slice(0, t.index + 1).filter((r) => typeof r === 'object').map((r) => r.gate);
        return `\`${t.flow.id}\` (${t.index + 1} items${g.length ? `; ${g.join(', ')}` : ''})`;
      })
      .join('<br>');
    L.push(`| **${cp.id}** | ${cp.description} | ${s.id} ${s.title} (${s.role}) | ${cp.verification} | ${cp.displayedStatus.en ?? '—'} / ${cp.displayedStatus.bm ?? '—'} | ${via} |`);
  }
  L.push('');
}
L.push('## Gates', '', '| Gate | Type | What the tester does |', '|---|---|---|');
for (const [id, g] of Object.entries(gates)) L.push(`| ${id} | ${g.type} | ${g.title} |`);
fs.writeFileSync(path.join(root, 'docs', 'status-catalog.md'), L.join('\n') + '\n');
console.log(`${targets.length} status specs in tests/status/en, docs/status-catalog.md written`);
