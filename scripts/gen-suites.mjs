// Generates, from registry/ and tests/cr-suites/<CR>/cr.json (run after changing either: npm run suites:gen):
//
//   tests/data-prep/en/<module>/<sub-module>/<flow>/<NN>-<STATUS>.spec.ts   one spec per status of each flow: runs it up to that
//                                                             status and stops (data preparation for manual testing)
//   tests/cr-suites/<CR>/data-prep/<SID>-<STATUS>.spec.ts      per CR scenario: prepare the data to its start status
//   tests/cr-suites/<CR>/execution/<SID>-<…>.spec.ts           per CR scenario: run the scenario from that status on
//   tests/cr-suites/<CR>/README.md                             the scenario table with commands, stop/end statuses
//   docs/status-catalog.md                                     every status per module + DB status + how to reach it
//   sql/status/<DOC>.sql                                       DBeaver queries: status history, current status, BPM tasks,
//                                                             all statuses of the document type (registry/db-schema.json)
// BM specs come with the BM phase, after permission. Plain Node, no packages.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const MODULES = ['pm', 'sm', 'qt', 'sq', 'dp', 'direct-loa', 'ct', 'fl'];
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const gates = read('registry/gates.json');
const dbSchema = read('registry/db-schema.json');
const dbStatuses = fs.existsSync(path.join(root, 'registry/db-statuses.json')) ? read('registry/db-statuses.json') : null;
const files = MODULES.map((m) => read(`registry/workflows/${m}.json`));
const steps = Object.fromEntries(files.flatMap((d) => Object.entries(d.steps).map(([id, s]) => [id, { id, module: d.module, ...s }])));
const flows = Object.fromEntries(files.flatMap((d) => d.flows.map((f) => [f.id, { submodule: 'main', ...f, module: d.module }])));
const key = (r) => (typeof r === 'string' ? r : r.gate);
const RANK = { execution: 0, documentation: 1, source: 2, unverified: 3 };
const rel = (f) => path.relative(root, f).split(path.sep).join('/');
const upTo = (file) => path.relative(path.dirname(file), root).split(path.sep).join('/');
const dbText = (db) => (db ? (db.statusId == null ? `${db.kind}: unchanged` : `${db.kind} ${db.statusId} ${db.en ?? ''}`) : '');
const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};
const HEADER = (src) => `// GENERATED by scripts/gen-suites.mjs from ${src} — do not edit; run "npm run suites:gen" after changing it.`;
const PW = (file) => `npx cross-env TEST_ENV=SIT playwright test "${rel(file)}" --project=flows --headed`;

/* ---------- tests/data-prep/en ---------- */
for (const old of ['tests/status', 'tests/data-prep/en']) fs.rmSync(path.join(root, old), { recursive: true, force: true });
const targets = []; // { flow, index, step, file }
for (const flow of Object.values(flows))
  flow.steps.forEach((r, index) => {
    if (typeof r !== 'string') return;
    const step = steps[r];
    const nn = String(index + 1).padStart(2, '0');
    const file = path.join(root, 'tests', 'data-prep', 'en', flow.module, flow.submodule, flow.id, `${nn}-${step.checkpoint.id}.spec.ts`);
    targets.push({ flow, index, step, file });
  });

for (const { flow, index, step, file } of targets) {
  const cp = step.checkpoint;
  const pathText = flow.steps.slice(0, index + 1).map((r) => (typeof r === 'string' ? `${r}${steps[r].automation === 'manual' ? ' (manual)' : ''}` : `GATE ${r.gate}`)).join(' → ');
  const gatesOnWay = flow.steps.slice(0, index + 1).filter((r) => typeof r === 'object').map((r) => r.gate);
  write(
    file,
    `${HEADER('registry/')}
//
// DATA PREP: ${flow.title}
// Module:    ${flow.module} / ${flow.submodule} · flow ${flow.id}
// Stops at:  ${cp.id} — ${cp.description} (after ${step.id}, ${step.role})
// DB status: ${dbText(cp.db) || 'not mapped yet (the run records what it sees)'}
// Path:      ${pathText}${gatesOnWay.length ? `\n// Gates:     ${gatesOnWay.join(', ')} — the run stops there until you record them (npm run qa -- gate …), then resume` : ''}
//
// Run:  ${PW(file)}
//   or: npm run qa -- prepare --env sit --flow ${flow.id} --status ${cp.id}
// Documents created: the run report, npm run qa -- data --env sit, or npm run qa -- doc-status --env sit --doc <number>
import { test } from '${upTo(file)}/fixtures/flow';
import { flowItems, flowTags, runItem, setupFlow } from '${upTo(file)}/support/core/flow-runner';
import { loadRegistry } from '${upTo(file)}/support/core/workflow-registry';

const LANG = 'EN';
const flow = loadRegistry().flows.get('${flow.id}')!;

test.describe(\`data-prep \${flow.id} → ${cp.id}\`, { tag: [...flowTags(flow, LANG), '@status-${cp.id}', '@data-prep'] }, () => {
  const runId = setupFlow(flow, LANG, { to: '${step.id}' });
  for (const { item, index, title, details } of flowItems(flow).slice(0, ${index + 1})) {
    test(title, details, async ({ page, appMessages, evidence }, testInfo) => {
      await runItem(flow, item, index, runId(), { page, appMessages, evidence }, testInfo);
    });
  }
});
`,
  );
}

/* ---------- tests/cr-suites/<CR> ---------- */
const crRoot = path.join(root, 'tests', 'cr-suites');
const crProblems = [];
const crSummaries = [];
for (const dir of fs.existsSync(crRoot) ? fs.readdirSync(crRoot) : []) {
  const defFile = path.join(crRoot, dir, 'cr.json');
  if (dir.startsWith('_') || !fs.existsSync(defFile)) continue;
  const cr = JSON.parse(fs.readFileSync(defFile, 'utf8'));
  for (const sub of ['data-prep', 'execution']) fs.rmSync(path.join(crRoot, dir, sub), { recursive: true, force: true });
  const rows = [];
  for (const sc of cr.scenarios) {
    const flow = flows[sc.flow];
    if (!flow) { crProblems.push(`${dir} ${sc.id}: unknown flow ${sc.flow}`); continue; }
    const keys = flow.steps.map(key);
    // "until" may be a step/gate ID or a status (checkpoint) ID of the flow
    const find = (v) => {
      if (!v) return -1;
      const byKey = keys.indexOf(v);
      if (byKey >= 0) return byKey;
      const idx = flow.steps.map((r, i) => (typeof r === 'string' && steps[r].checkpoint.id === v ? i : -1)).filter((i) => i >= 0);
      if (idx.length > 1) crProblems.push(`${dir} ${sc.id}: status ${v} occurs ${idx.length} times in ${flow.id}; give the step ID`);
      return idx[0] ?? -1;
    };
    const prepIdx = find(sc.prepare?.until);
    const execIdx = sc.execute ? (sc.execute.until ? find(sc.execute.until) : keys.length - 1) : -1;
    if (sc.prepare?.until && prepIdx < 0) crProblems.push(`${dir} ${sc.id}: prepare.until ${sc.prepare.until} not in ${flow.id}`);
    if (sc.execute && execIdx < 0) crProblems.push(`${dir} ${sc.id}: execute.until ${sc.execute.until} not in ${flow.id}`);
    if (sc.execute && execIdx <= prepIdx) crProblems.push(`${dir} ${sc.id}: execute.until must come after prepare.until`);
    const prepStep = prepIdx >= 0 && typeof flow.steps[prepIdx] === 'string' ? steps[flow.steps[prepIdx]] : null;
    const prepStatus = prepIdx >= 0 ? (prepStep ? prepStep.checkpoint.id : `GATE ${keys[prepIdx]}`) : null;
    const execStep = execIdx >= 0 && typeof flow.steps[execIdx] === 'string' ? steps[flow.steps[execIdx]] : null;
    const prefix = `CR-${cr.cr}_${sc.id}`;
    const slug = (s) => s.replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 50);
    const tag = `'@cr-${cr.cr}', '@scenario-${cr.cr}-${sc.id}'`;
    const row = { sc, flow, prepStatus, prepStep, execStep, prepFile: null, execFile: null };

    if (prepIdx >= 0) {
      const file = path.join(crRoot, dir, 'data-prep', `${sc.id}-${prepStatus.replace(/\s+/g, '_')}.spec.ts`);
      row.prepFile = file;
      write(
        file,
        `${HEADER(`tests/cr-suites/${dir}/cr.json`)}
//
// CR ${cr.cr} · ${sc.id} ${sc.title}
// DATA PREP: flow ${flow.id} up to ${keys[prepIdx]} → stops at ${prepStatus}${prepStep?.checkpoint.db ? ` (DB ${dbText(prepStep.checkpoint.db)})` : ''}
// Run:  ${PW(file)}
// Then: ${sc.execute ? `the execution spec execution/${sc.id}-*.spec.ts (it takes the documents of this run)` : 'execute the scenario by hand (README.md)'}
import { test } from '${upTo(file)}/fixtures/flow';
import { flowItems, flowTags, runItem, setupFlow } from '${upTo(file)}/support/core/flow-runner';
import { loadRegistry } from '${upTo(file)}/support/core/workflow-registry';

const LANG = 'EN';
const flow = loadRegistry().flows.get('${flow.id}')!;

test.describe('CR ${cr.cr} ${sc.id} data-prep → ${prepStatus}', { tag: [...flowTags(flow, LANG), ${tag}, '@data-prep'] }, () => {
  const runId = setupFlow(flow, LANG, { to: '${keys[prepIdx]}', runPrefix: '${prefix}_prep', cr: '${cr.cr}' });
  for (const { item, index, title, details } of flowItems(flow).slice(0, ${prepIdx + 1})) {
    test(title, details, async ({ page, appMessages, evidence }, testInfo) => {
      await runItem(flow, item, index, runId(), { page, appMessages, evidence }, testInfo);
    });
  }
});
`,
      );
    }
    if (sc.execute && execIdx >= 0) {
      const from = keys[prepIdx + 1];
      const file = path.join(crRoot, dir, 'execution', `${sc.id}-${slug(sc.title)}.spec.ts`);
      row.execFile = file;
      write(
        file,
        `${HEADER(`tests/cr-suites/${dir}/cr.json`)}
//
// CR ${cr.cr} · ${sc.id} ${sc.title}
// EXECUTION: flow ${flow.id} from ${from} to ${keys[execIdx]}${execStep ? ` → ${execStep.checkpoint.id}${execStep.checkpoint.db ? ` (DB ${dbText(execStep.checkpoint.db)})` : ''}` : ''}
// Expected:  ${sc.expected ?? (execStep ? execStep.checkpoint.description : '')}
${prepIdx >= 0 ? `// Needs:     data prepared by data-prep/${path.basename(row.prepFile)} (latest completed run "${prefix}_prep_…"),
//            or QA_INPUT="${(steps[from]?.inputs ?? []).map((i) => `${i.doc}=<number>`).join(',') || 'DOC=<number>'}". It must still be at ${prepStatus}, else the run blocks.
` : ''}// Run:       ${PW(file)}
import { test } from '${upTo(file)}/fixtures/flow';
import { flowItems, flowTags, runItem, setupFlow } from '${upTo(file)}/support/core/flow-runner';
import { loadRegistry } from '${upTo(file)}/support/core/workflow-registry';

const LANG = 'EN';
const flow = loadRegistry().flows.get('${flow.id}')!;

test.describe('CR ${cr.cr} ${sc.id} execution: ${sc.title.replace(/'/g, "\\'")}', { tag: [...flowTags(flow, LANG), ${tag}, '@execution'] }, () => {
  const runId = setupFlow(flow, LANG, { ${prepIdx >= 0 ? `from: '${from}', ` : ''}to: '${keys[execIdx]}', runPrefix: '${prefix}_exec', ${prepIdx >= 0 ? `inputsFrom: '${prefix}_prep', ` : ''}cr: '${cr.cr}' });
  for (const { item, index, title, details } of flowItems(flow).slice(${prepIdx + 1}, ${execIdx + 1})) {
    test(title, details, async ({ page, appMessages, evidence }, testInfo) => {
      await runItem(flow, item, index, runId(), { page, appMessages, evidence }, testInfo);
    });
  }
});
`,
      );
    }
    rows.push(row);
  }
  // README of the CR suite
  const L = [
    `# CR ${cr.cr} — ${cr.title}`,
    '',
    '> Generated by `npm run suites:gen` from `cr.json`. Edit `cr.json`, not this file.',
    '',
    cr.notes ?? '',
    '',
    `Environment **SIT** · language **${cr.language ?? 'EN'}** · evidence under \`evidence/SIT/${cr.cr}/\` · runs in \`.data/SIT/<tester>/runs/CR-${cr.cr}_*\``,
    '',
    '## How to use',
    '',
    '1. **Data prep** — run the scenario\'s data-prep spec. It stops at the start status; the documents are in the run report.',
    '2. **Execution** — either run the execution spec (it takes the prepared documents and first checks in the SIT database',
    '   that they are still at the start status), or execute the scenario by hand on the prepared documents.',
    '3. Check a document any time: `npm run qa -- doc-status --env sit --doc <number>` (status history EN/BM + open BPM tasks).',
    '',
    '| Scenario | Flow | Data prep stops at | Execution ends at | Expected | Specs |',
    '|---|---|---|---|---|---|',
  ];
  for (const r of rows) {
    const prep = r.prepStatus ? `**${r.prepStatus}**${r.prepStep?.checkpoint.db ? `<br>DB ${dbText(r.prepStep.checkpoint.db)}` : ''}` : '— (starts from scratch)';
    const exec = r.execStep ? `**${r.execStep.checkpoint.id}**${r.execStep.checkpoint.db ? `<br>DB ${dbText(r.execStep.checkpoint.db)}` : ''}` : r.sc.execute ? '' : 'manual (by the tester)';
    const specs = [r.prepFile && `[data-prep](${path.relative(path.join(crRoot, dir), r.prepFile).split(path.sep).join('/')})`, r.execFile && `[execution](${path.relative(path.join(crRoot, dir), r.execFile).split(path.sep).join('/')})`].filter(Boolean).join(' · ');
    L.push(`| ${r.sc.id} ${r.sc.title} | \`${r.flow.id}\` | ${prep} | ${exec} | ${r.sc.expected ?? ''} | ${specs} |`);
  }
  L.push('', '## Commands', '');
  for (const r of rows) {
    L.push(`**${r.sc.id} ${r.sc.title}**`, '');
    if (r.prepFile) L.push('```', PW(r.prepFile), '```');
    if (r.execFile) L.push('```', PW(r.execFile), '```');
    if (r.sc.manual) L.push(`Manual execution: ${r.sc.manual}`);
    L.push('');
  }
  write(path.join(crRoot, dir, 'README.md'), L.join('\n') + '\n');
  crSummaries.push(`${cr.cr}: ${rows.length} scenarios`);
}
if (crProblems.length) {
  console.error(`cr-suites problems:\n- ${crProblems.join('\n- ')}`);
  process.exitCode = 1;
}

/* ---------- sql/status/<DOC>.sql ---------- */
const sqlDir = path.join(root, 'sql', 'status');
fs.rmSync(sqlDir, { recursive: true, force: true });
const historySql = (doc, src, wfType) => {
  const ids = src.subIds?.[wfType] ?? `select ${src.id} from ngep_sit.${src.table} where ${src.no} = '{NO}'`;
  return `select w.doc_type, w.status_id, w.is_current, to_char(w.created_date, 'YYYY-MM-DD HH24:MI:SS') as changed_at,
       (select e.status_name from ngep_sit.pm_status_desc e where e.status_id = w.status_id and e.language_code = 'en' and rownum = 1) as status_en,
       (select m.status_name from ngep_sit.pm_status_desc m where m.status_id = w.status_id and m.language_code = 'ms' and rownum = 1) as status_bm
  from ngep_sit.${src.workflow} w
 where w.doc_type ${wfType === '*' ? `in (${src.wfTypes.map((t) => `'${t}'`).join(', ')})` : `= '${wfType}'`}
   and w.doc_id in (${ids})
 order by w.created_date, w.workflow_status_id;`;
};
for (const [doc, src] of Object.entries(dbSchema.documents)) {
  const ex = { QT: 'QT260000000004342', SQ: 'SQ260000000002363', RN: 'RN260000000004908', LA: 'LA260000000004216', CT: 'CT260000000002293', CR: 'CR260000000006053', CO: 'CO260000000006651' }[doc] ?? `${doc}26…`;
  const L = [
    `-- GENERATED by scripts/gen-suites.mjs from registry/db-schema.json — ${doc} ${src.name}. READ-ONLY queries for DBeaver, SIT connection only.`,
    `-- Replace {NO} with the document number (e.g. ${ex}). Mapping verified: ${src.verified ? 'yes' : 'NO (pattern only)'} — ${src.evidence}`,
    '',
  ];
  const types = src.wfTypes.length > 1 && !src.subIds ? ['*', ...src.wfTypes] : src.wfTypes;
  for (const t of types) {
    L.push(`-- Status history${t === '*' ? ' (every workflow type: the whole path)' : ` (${t})`}; the row with is_current = 1 is the current status`);
    L.push(historySql(doc, src, t), '');
  }
  L.push('-- Open BPM tasks: who the task is assigned to (task name = activityname)');
  L.push(`select activityname, state, assignees, acquiredby, to_char(createddate, 'YYYY-MM-DD HH24:MI:SS') as created
  from ${dbSchema.bpmTasks}
 where customattributestring1 = '{NO}'
 order by createddate;`, '');
  for (const t of src.wfTypes) {
    L.push(`-- Every status a ${t} has used on SIT in the last year (EN/BM), to see where a document can stop`);
    L.push(`select w.status_id, count(*) as rows_,
       (select e.status_name from ngep_sit.pm_status_desc e where e.status_id = w.status_id and e.language_code = 'en' and rownum = 1) as status_en,
       (select m.status_name from ngep_sit.pm_status_desc m where m.status_id = w.status_id and m.language_code = 'ms' and rownum = 1) as status_bm
  from ngep_sit.${src.workflow} w
 where w.doc_type = '${t}' and w.created_date > sysdate - 365
 group by w.status_id order by w.status_id;`, '');
  }
  write(path.join(sqlDir, `${doc}.sql`), L.join('\n'));
}

/* ---------- docs/status-catalog.md ---------- */
const L = [
  '# Status catalogue (generated)',
  '',
  'Generated by `npm run suites:gen` from `registry/`. Every status (checkpoint) the automation can reach, per module: the SIT',
  'database status it shows, and how to prepare a transaction there for **manual testing**. Do not edit by hand.',
  '',
  '- **Data prep by CLI:** `npm run qa -- prepare --env sit --status <STATUS>` (best-verified flow; `--flow <id>` to choose).',
  '- **Data prep by spec:** `npx cross-env TEST_ENV=SIT playwright test "tests/data-prep/en/<module>/<sub-module>/<flow>/<NN>-<STATUS>.spec.ts" --project=flows --headed`.',
  '- **Pick and choose for a CR:** `npm run qa -- cr add --cr <CR>` (module → sub-module → flow → start status → end status).',
  '- **CR suites** (data prep + execution per scenario): `tests/cr-suites/<CR>/README.md`.',
  '- **Check a document:** `npm run qa -- doc-status --env sit --doc <number>`, or the DBeaver queries in `sql/status/<DOC>.sql`.',
  '- A path through a **gate** stops there until you record it (`npm run qa -- gate …`), then `npm run qa -- resume`.',
  '- A **manual** step (QT for now) stops the run: do it in the application, `npm run qa -- reconcile … --done`, resume; the DB status confirms it.',
  '- *DB status* = SC/CT/FL_WORKFLOW_STATUS with PM_STATUS_DESC names (what the screens show). "—" = not mapped yet.',
  '',
];
L.push('## Modules, sub-modules and flows', '', '| Module | Sub-module | Flows (statuses you can stop at) |', '|---|---|---|');
for (const d of files) {
  const bySub = new Map();
  for (const f of Object.values(flows).filter((x) => x.module === d.module)) (bySub.get(f.submodule) ?? bySub.set(f.submodule, []).get(f.submodule)).push(f);
  const tick = '`';
  for (const [sub, fs_] of bySub) L.push(`| ${d.module} | ${sub} | ${fs_.map((f) => `${tick}${f.id}${tick} (${f.steps.filter((r) => typeof r === 'string').length})`).join(', ')} |`);
}
L.push('');
for (const d of files) {
  L.push(`## ${d.module} — ${d.name}`, '', d.description, '');
  L.push('| Status | Meaning | After step (role) | DB status (EN / BM) | Verified | Reached by flows: sub-module / flow (gates on the way) |', '|---|---|---|---|---|---|');
  const byCp = new Map();
  for (const t of targets.filter((t) => t.step.module === d.module)) {
    const k = `${t.step.checkpoint.id}|${t.step.id}`;
    if (!byCp.has(k)) byCp.set(k, []);
    byCp.get(k).push(t);
  }
  for (const [, ts] of byCp) {
    const s = ts[0].step;
    const cp = s.checkpoint;
    ts.sort((a, b) => RANK[a.flow.verification] - RANK[b.flow.verification] || a.index - b.index);
    const via = ts
      .map((t) => {
        const g = t.flow.steps.slice(0, t.index + 1).filter((r) => typeof r === 'object').map((r) => r.gate);
        return `${t.flow.submodule} / \`${t.flow.id}\` (${t.index + 1} items${g.length ? `; ${g.join(', ')}` : ''})`;
      })
      .join('<br>');
    const db = cp.db ? `${cp.db.kind} **${cp.db.statusId ?? '—'}** ${cp.db.en ?? ''} / ${cp.db.bm ?? ''}${cp.db.observeOnly ? ' *(expected, not yet seen on SIT)*' : ''}` : '—';
    L.push(`| **${cp.id}** | ${cp.description} | ${s.id}${s.automation === 'manual' ? ' (manual)' : ''} ${s.title} (${s.role}) | ${db} | ${cp.verification} | ${via} |`);
  }
  L.push('');
}
L.push('## Gates', '', '| Gate | Type | What the tester does | DB status afterwards |', '|---|---|---|---|');
for (const [id, g] of Object.entries(gates)) L.push(`| ${id} | ${g.type} | ${g.title} | ${g.db ? `${g.db.kind} ${g.db.statusId} ${g.db.en}` : ''} |`);
L.push('', '## Every status per document type on SIT', '');
if (!dbStatuses) L.push('Not read yet: `npm run qa -- db-catalog --env sit` reads them from the SIT database into `registry/db-statuses.json`.');
else {
  L.push(`Read from SIT ${dbStatuses.readAt} (last ${dbStatuses.days} days of workflow rows): \`npm run qa -- db-catalog --env sit\` refreshes it.`, '');
  for (const [k, list] of Object.entries(dbStatuses.statuses)) {
    L.push(`### ${k}`, '', '| Status ID | EN | BM | Rows |', '|---|---|---|---|');
    for (const x of list) L.push(`| ${x.statusId} | ${x.en} | ${x.bm} | ${x.rows} |`);
    L.push('');
  }
}
fs.writeFileSync(path.join(root, 'docs', 'status-catalog.md'), L.join('\n') + '\n');
console.log(`${targets.length} data-prep specs (tests/data-prep/en), ${crSummaries.length} CR suite(s) (${crSummaries.join('; ') || 'none'}), sql/status/*.sql, docs/status-catalog.md`);
