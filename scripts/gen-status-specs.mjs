// One data-prep spec for EVERY active status of the status list (registry/active-statuses.json, from
// NGEPSIT_Active_Status_All_Modules.xlsx):  tests/data-prep/en/by-status/<module>/<doc type>/<status id>-<name>.spec.ts
//
//   method 'flow'      a flow step reaches the status → run the flow up to that step, then confirm the DB status
//   method 'simulate'  no flow reaches it (backend-only, never used, or no flow yet) → make the document with the best flow
//                      (or take it from QA_INPUT), then simulate the status: the run plans the data patch, the tester runs
//                      it in DBeaver, rerunning the same spec continues the run and confirms the status
//   unmapped           the doc type has no DB mapping yet (registry/db-schema.json) → spec is fixme with the reason
// Also writes registry/status-specs.json (used by scripts/status-coverage.mjs and `qa prepare --status-id`).
// Run: node scripts/gen-status-specs.mjs   (npm run suites:gen runs it too)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
if (!fs.existsSync(path.join(root, 'registry/active-statuses.json'))) {
  console.log('no registry/active-statuses.json: run node scripts/import-active-statuses.mjs <xlsx> first');
  process.exit(0);
}
const active = read('registry/active-statuses.json').statuses;
const usage = fs.existsSync(path.join(root, 'registry/db-usage.json')) ? read('registry/db-usage.json').usage : {};
const typeUsed = (m, t) => Object.keys(usage).some((k) => k.startsWith(`${m}|${t}|`));
const schema = read('registry/db-schema.json');
const MODULES = ['pm', 'sm', 'qt', 'sq', 'dp', 'direct-loa', 'ct', 'fl'];
const files = MODULES.map((m) => read(`registry/workflows/${m}.json`));
const steps = Object.fromEntries(files.flatMap((d) => Object.entries(d.steps).map(([id, s]) => [id, { id, module: d.module, ...s }])));
const flows = files.flatMap((d) => d.flows.map((f) => ({ submodule: 'main', ...f, module: d.module })));
const RANK = { execution: 0, documentation: 1, source: 2, unverified: 3 };

// Excel module + workflow doc type → our document + status kind (same rule as support/core/simulate.ts kindOfWorkflow)
const kindOf = (module, wf) => {
  for (const [doc, src] of Object.entries(schema.documents)) {
    if (src.workflow.split('_')[0].toUpperCase() !== module || !src.wfTypes.includes(wf)) continue;
    return { doc, kind: wf === src.wfTypes[0] && wf === doc && !src.subIds ? doc : `${doc}:${wf}` };
  }
  return null;
};
// 'AP' and 'AP:SR' are the same status track: compare as DOC:WFTYPE (default = the doc's first workflow type)
const norm = (k) => { const [d, w] = k.split(':'); return `${d}:${w ?? schema.documents[d]?.wfTypes[0] ?? d}`; };
const sameKind = (a, b) => norm(a) === norm(b);
const docOfKind = (k) => k.split(':')[0];

// every (flow, index) where a step's checkpoint.db is known, or a step outputs a document
const points = [];
for (const f of flows)
  f.steps.forEach((r, i) => {
    if (typeof r !== 'string') return;
    const s = steps[r];
    const score = RANK[f.verification] * 100 + (s.automation === 'manual' ? 50 : 0) + f.steps.slice(0, i + 1).filter((x) => typeof x === 'object').length * 10 + i;
    points.push({ flow: f, index: i, step: s, score });
  });
const reachOf = (kind, statusId) =>
  points.filter((p) => p.step.checkpoint.db && sameKind(p.step.checkpoint.db.kind, kind) && p.step.checkpoint.db.statusId === statusId).sort((a, b) => a.score - b.score)[0];
// earliest point where the document exists (it is an output, or a checkpoint reads its status)
const baseOf = (doc) =>
  points
    .filter((p) => p.step.outputs.some((o) => o.doc === doc) || (p.step.checkpoint.db && docOfKind(p.step.checkpoint.db.kind) === doc))
    .sort((a, b) => a.score - b.score)[0];

const outRoot = path.join(root, 'tests', 'data-prep', 'en', 'by-status');
fs.rmSync(outRoot, { recursive: true, force: true });
const slug = (t) => t.replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || 'status';
const q = (s) => JSON.stringify(s);
const index = {};
const counts = { flow: 0, simulateWithFlow: 0, simulateInput: 0, unmapped: 0 };

for (const s of active) {
  const map = kindOf(s.module, s.docType);
  const file = path.join(outRoot, s.module.toLowerCase(), s.docType, `${s.statusId}-${slug(s.en)}.spec.ts`);
  const up = path.relative(path.dirname(file), root).split(path.sep).join('/');
  const rel = path.relative(root, file).split(path.sep).join('/');
  const prefix = `status-${s.module}-${s.docType}-${s.statusId}`;
  const tag = `'@data-prep', '@by-status', '@status-id-${s.statusId}', '@module-${s.module.toLowerCase()}', '@doctype-${s.docType}'`;
  const head = `// GENERATED by scripts/gen-status-specs.mjs from registry/active-statuses.json — do not edit.
//
// STATUS ${s.module} / ${s.docType} / ${s.statusId}: ${s.en} | ${s.bm}`;
  const run = `// Run:  npx cross-env TEST_ENV=SIT playwright test "${rel}" --project=flows --headed
//   or: npm run qa -- prepare --env sit --status-id ${s.statusId} --doc-type ${s.docType}`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!map) {
    const used = typeUsed(s.module, s.docType);
    counts.unmapped++;
    index[`${s.module}|${s.docType}|${s.statusId}`] = { spec: rel, method: used ? 'unmapped' : 'never-used-type' };
    fs.writeFileSync(file, `${head}
${used ? `// NOT MAPPED YET: no table for ${s.module} doc type ${s.docType} in registry/db-schema.json, so the document cannot be found or
// simulated. Map it (table, number and id columns, workflow table) and regenerate.` : `// NEVER USED ON SIT: no ${s.module} document has ever been in the ${s.docType} workflow, so there is nothing to prepare or simulate
// (a simulation moves an existing document's status). Ask the developer whether this workflow is still used / how it starts.`}
${run}
import { test } from '${up}/fixtures/flow';

test.describe(${q(`status ${s.module} ${s.docType} ${s.statusId} ${s.en}`)}, { tag: [${tag}] }, () => {
  test.fixme(true, ${q(used ? `${s.module} doc type ${s.docType} has no database mapping yet (registry/db-schema.json)` : `${s.module} doc type ${s.docType} has never been used on SIT: nothing to prepare; ask the developer`)});
  test(${q(`reach ${s.statusId} ${s.en}`)}, async () => {});
});
`);
    continue;
  }
  const reach = reachOf(map.kind, s.statusId);
  const base = reach ?? baseOf(map.doc);
  const method = reach ? 'flow' : 'simulate';
  const target = { module: s.module, docType: s.docType, statusId: s.statusId, en: s.en, bm: s.bm, doc: map.doc, kind: map.kind, method };
  if (reach) counts.flow++;
  else if (base) counts.simulateWithFlow++;
  else counts.simulateInput++;
  index[`${s.module}|${s.docType}|${s.statusId}`] = { spec: rel, method, flow: base?.flow.id ?? null, upTo: base?.step.id ?? null, manual: base?.step.automation === 'manual' };
  const how = reach
    ? `// HOW: flow ${reach.flow.module}/${reach.flow.submodule}/${reach.flow.id} up to ${reach.step.id} (${reach.step.title}), then the DB status is confirmed.`
    : base
      ? `// HOW: flow ${base.flow.module}/${base.flow.submodule}/${base.flow.id} up to ${base.step.id} makes the ${map.doc}; then the status is SIMULATED
//      (no flow of ours reaches it): the run plans the data patch, you run it in DBeaver, rerun this spec to confirm.`
      : `// HOW: no flow makes a ${map.doc} yet: give one with QA_INPUT=${map.doc}=<number> (already in the ${s.docType} workflow);
//      the status is then SIMULATED: the run plans the data patch, you run it in DBeaver, rerun this spec to confirm.`;
  const body = base
    ? `const flow = loadRegistry().flows.get(${q(base.flow.id)})!;

test.describe(${q(`status ${s.module} ${s.docType} ${s.statusId} ${s.en}`)}, { tag: [...flowTags(flow, LANG), ${tag}] }, () => {
  const runId = setupFlow(flow, LANG, { to: ${q(base.step.id)}, runPrefix: ${q(prefix)}, resumeLatest: true });
  for (const { item, index, title, details } of flowItems(flow).slice(0, ${base.index + 1})) {
    test(title, details, async ({ page, appMessages, evidence }, testInfo) => {
      test.skip(hasInput(TARGET.doc), TARGET.doc + ' given with QA_INPUT: no new document is made');
      await runItem(flow, item, index, runId(), { page, appMessages, evidence }, testInfo);
    });
  }
  test(${q(`reach ${s.statusId} ${s.en}`)}, async ({ page, appMessages, evidence }, testInfo) => {
    await reachStatus(TARGET, runId(), { page, appMessages, evidence }, testInfo);
  });
});
`
    : `test.describe(${q(`status ${s.module} ${s.docType} ${s.statusId} ${s.en}`)}, { tag: [${tag}] }, () => {
  test(${q(`reach ${s.statusId} ${s.en}`)}, async ({ page, appMessages, evidence }, testInfo) => {
    await reachStatus(TARGET, undefined, { page, appMessages, evidence }, testInfo);
  });
});
`;
  fs.writeFileSync(file, `${head}
${how}
${run}
import { test } from '${up}/fixtures/flow';
import { ${base ? 'flowItems, flowTags, hasInput, reachStatus, runItem, setupFlow, ' : 'reachStatus, '}type StatusTarget } from '${up}/support/core/flow-runner';
${base ? `import { loadRegistry } from '${up}/support/core/workflow-registry';\n` : ''}
${base ? "const LANG = 'EN';\n" : ''}const TARGET: StatusTarget = ${JSON.stringify(target)};
${body}`);
}
fs.writeFileSync(path.join(root, 'registry', 'status-specs.json'), JSON.stringify({ _about: 'GENERATED by scripts/gen-status-specs.mjs — key = MODULE|DOC_TYPE|STATUS_ID', counts, index }, null, 1) + '\n');
console.log(`${active.length} status specs in tests/data-prep/en/by-status:`, JSON.stringify(counts));
